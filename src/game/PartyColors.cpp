static const char* kImages[kImageCount] = { "F01", "F60", "C00", "A00" };


const char*
ImageCode(int index)
{
    return index >= 0 && index < kImageCount ? kImages[index] : "";
}


int
ImageIndex(const std::string& image)
{
    for (int i = 0; i < kImageCount; i++) {
        if (image == kImages[i])
            return i;
    }
    return -1;
}


bool
ApplyColorPreset(std::vector<uint8>& colors, int key,
    const std::string& image, int step)
{
    const int which = ImageIndex(image);
    if (key < 1 || key > 3 || which < 0 || step < 0 || step > 5)
        return false;
    if (colors.size() < size_t(kFigureColorBytes))
        colors.resize(size_t(kFigureColorBytes), 32);
    const color_preset& preset = kColorPresets[key - 1][which][step];
    for (int i = 0; i < preset.count; i++)
        colors[preset.writes[i].offset] = preset.writes[i].value;
    return true;
}
